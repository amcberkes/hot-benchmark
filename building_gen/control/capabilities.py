EnumT = TypeVar("EnumT", bound=Enum)


def _exact_text(value: Any, *, field_name: str) -> str:
    if not isinstance(value, str):
        raise TypeError(f"{field_name} must be a string")
    # ``str`` subclasses can override ``__eq__``, ``casefold``, ``strip``, and
    # ``__str__``.  Own the real string payload through the base implementation
    # before invoking any operation that could otherwise dispatch virtually.
    value = str.__str__(value)
    if not value or value != str.strip(value):
        raise ValueError(f"{field_name} must be non-empty and cannot have surrounding whitespace")
    return value


def _identifier(value: Any, *, field_name: str) -> str:
    value = _exact_text(value, field_name=field_name)
    if not _IDENTIFIER_RE.fullmatch(value):
        raise ValueError(f"{field_name} must use lowercase letters, digits, '.', '_' or '-'")
    return value


def _enum(value: Any, enum_type: type[EnumT], *, field_name: str) -> EnumT:
    if isinstance(value, enum_type):
        return value
    if not isinstance(value, str):
        raise TypeError(f"{field_name} must be a string or {enum_type.__name__}")
    value = str.__str__(value)
    try:
        return enum_type(value)
    except ValueError as error:
        expected = ", ".join(sorted(repr(item.value) for item in enum_type))
        raise ValueError(f"{field_name} must be one of: {expected}") from error


def _sha256(value: Any, *, field_name: str) -> str:
    value = _exact_text(value, field_name=field_name)
    if not _SHA256_RE.fullmatch(value):
        raise ValueError(f"{field_name} must contain exactly 64 lowercase hexadecimal characters")
    return value


def _optional_sha256(value: Any, *, field_name: str) -> str | None:
    if value is None:
        return None
    return _sha256(value, field_name=field_name)


def _finite_float(value: Any, *, field_name: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise TypeError(f"{field_name} must be a finite numeric value")
    normalized = float(value)
    if not math.isfinite(normalized):
        raise ValueError(f"{field_name} must be a finite numeric value")
    # JSON distinguishes -0.0 textually even though IEEE equality does not.
    # Scientific hashes must have one representation for mathematical zero.
    if normalized == 0.0:
        normalized = 0.0
    return normalized


def _tuple(value: Any, *, field_name: str) -> tuple[Any, ...]:
    if isinstance(value, (str, bytes, bytearray)) or not isinstance(value, Sequence):
        raise TypeError(f"{field_name} must be a sequence")
    return tuple(value)


def _typed_tuple(value: Any, item_type: type[Any], *, field_name: str) -> tuple[Any, ...]:
    values = _tuple(value, field_name=field_name)
    if any(not isinstance(item, item_type) for item in values):
        raise TypeError(f"{field_name} must contain only {item_type.__name__} values")
    return values


def _casefold_unique(values: Sequence[str], *, field_name: str) -> None:
    seen: dict[str, str] = {}
    for value in values:
        folded = value.casefold()
        previous = seen.get(folded)
        if previous is not None:
            raise ValueError(f"{field_name} must be unique ignoring case; {previous!r} conflicts with {value!r}")
        seen[folded] = value


def _casefold_tuple_unique(values: Sequence[tuple[str, ...]], *, field_name: str) -> None:
    seen: dict[tuple[str, ...], tuple[str, ...]] = {}
    for value in values:
        folded = tuple(item.casefold() for item in value)
        previous = seen.get(folded)
        if previous is not None:
            raise ValueError(f"{field_name} must be unique ignoring case; {previous!r} conflicts with {value!r}")
        seen[folded] = value


def _canonical_json(value: Any) -> str:
    return json.dumps(
        value,
        ensure_ascii=False,
        allow_nan=False,
        sort_keys=True,
        separators=(",", ":"),
    )


def _domain_sha256(namespace: str, payload: Any) -> str:
    return hashlib.sha256(namespace.encode("utf-8") + b"\x00" + _canonical_json(payload).encode("utf-8")).hexdigest()


def energyplus_topology_node_id(
    kind: TopologyNodeKind | str,
    object_type: str,
    object_name: str,
) -> str:
    """Return the stable node ID derived only from EnergyPlus identity."""

    normalized_kind = _enum(kind, TopologyNodeKind, field_name="kind")
    normalized_type = _exact_text(object_type, field_name="object_type")
    normalized_name = _exact_text(object_name, field_name="object_name")
    digest = _domain_sha256(
        "HOT EnergyPlus topology node",
        {
            "kind": normalized_kind.value,
            "object_type": normalized_type.casefold(),
            "object_name": normalized_name.casefold(),
        },
    )
    return f"{normalized_kind.value}-{digest[:24]}"


def energyplus_actuator_endpoint_id(
    component_type: str,
    control_type: str,
    component_name: str,
) -> str:
    """Return the stable actuator ID derived only from its EnergyPlus triple."""

    triple = {
        "component_type": _exact_text(component_type, field_name="component_type"),
        "control_type": _exact_text(control_type, field_name="control_type"),
        "component_name": _exact_text(component_name, field_name="component_name"),
    }
    digest = _domain_sha256(
        "HOT EnergyPlus actuator endpoint",
        {key: value.casefold() for key, value in triple.items()},
    )
    return f"actuator-{digest[:24]}"


def energyplus_output_variable_id(variable_name: str, key_value: str) -> str:
    """Return the stable output ID derived only from its EnergyPlus pair."""

    pair = {
        "variable_name": _exact_text(variable_name, field_name="variable_name"),
        "key_value": _exact_text(key_value, field_name="key_value"),
    }
    digest = _domain_sha256(
        "HOT EnergyPlus output variable",
        {key: value.casefold() for key, value in pair.items()},
    )
    return f"output-variable-{digest[:24]}"


def _exact_keys(
    value: Any,
    *,
    required: frozenset[str],
    optional: frozenset[str] = frozenset(),
    field_name: str,
) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise TypeError(f"{field_name} must be a mapping")
    owned: dict[str, Any] = {}
    for raw_key, item in value.items():
        if not isinstance(raw_key, str):
            raise TypeError(f"{field_name} keys must be strings")
        key = str.__str__(raw_key)
        if key in owned:
            raise ValueError(f"{field_name} contains duplicate key {key!r}")
        owned[key] = item
    keys = set(owned)
    missing = sorted(required - keys)
    unknown = sorted(keys - required - optional)
    if missing or unknown:
        raise ValueError(f"{field_name} has missing keys {missing!r} and unknown keys {unknown!r}")
    return owned


@dataclass(frozen=True, slots=True)
class UpstreamSourcePin:
    """Exact Building2Building paper-release source and license pin."""

    repository_url: str = BUILDING2BUILDING_REPOSITORY_URL
    tag: str = BUILDING2BUILDING_TAG
    commit: str = BUILDING2BUILDING_COMMIT
    license_spdx: str = BUILDING2BUILDING_LICENSE_SPDX
    license_url: str = BUILDING2BUILDING_LICENSE_URL

    def __post_init__(self) -> None:
        field_names = (
            "repository_url",
            "tag",
            "commit",
            "license_spdx",
            "license_url",
        )
        actual = tuple(_exact_text(getattr(self, field_name), field_name=field_name) for field_name in field_names)
        for field_name, value in zip(field_names, actual):
            object.__setattr__(self, field_name, value)
        expected = (
            BUILDING2BUILDING_REPOSITORY_URL,
            BUILDING2BUILDING_TAG,
            BUILDING2BUILDING_COMMIT,
            BUILDING2BUILDING_LICENSE_SPDX,
            BUILDING2BUILDING_LICENSE_URL,
        )
        if actual != expected:
            raise ValueError("Building2Building provenance must match the pinned v1.0.0 paper release")

    def to_dict(self) -> dict[str, str]:
        return {
            "repository_url": self.repository_url,
            "tag": self.tag,
            "commit": self.commit,
            "license_spdx": self.license_spdx,
            "license_url": self.license_url,
        }

    @classmethod
    def from_dict(cls, value: Any) -> UpstreamSourcePin:
        item = _exact_keys(
            value,
            required=frozenset(
                {
                    "repository_url",
                    "tag",
                    "commit",
                    "license_spdx",
                    "license_url",
                }
            ),
            field_name="upstream",
        )
        return cls(**item)


@dataclass(frozen=True, slots=True)
class BoundRequirement:
    """One side of a profile bound with independently auditable provenance."""

    allowed_sources: tuple[BoundSource, ...]
    exact_value: float | None = None
    engineering_fallback_value: float | None = None

    def __post_init__(self) -> None:
        sources = tuple(
            _enum(item, BoundSource, field_name="bound source")
            for item in _tuple(self.allowed_sources, field_name="allowed_sources")
        )
        if not sources:
            raise ValueError("allowed_sources cannot be empty")
        _casefold_unique(tuple(item.value for item in sources), field_name="allowed_sources")
        object.__setattr__(
            self,
            "allowed_sources",
            tuple(sorted(sources, key=lambda item: item.value)),
        )
        exact = None if self.exact_value is None else _finite_float(self.exact_value, field_name="exact_value")
        fallback = (
            None
            if self.engineering_fallback_value is None
            else _finite_float(
                self.engineering_fallback_value,
                field_name="engineering_fallback_value",
            )
        )
        if exact is not None and fallback is not None:
            raise ValueError("a bound requirement cannot declare both exact and fallback values")
        if fallback is not None and BoundSource.ENGINEERING_FALLBACK not in sources:
            raise ValueError("engineering_fallback_value requires ENGINEERING_FALLBACK provenance")
        object.__setattr__(self, "exact_value", exact)
        object.__setattr__(self, "engineering_fallback_value", fallback)

    def validate(self, value: float, source: BoundSource, *, field_name: str) -> None:
        if source not in self.allowed_sources:
            allowed = ", ".join(item.value for item in self.allowed_sources)
            raise ValueError(f"{field_name} provenance {source.value!r} is not allowed; expected {allowed}")
        if self.exact_value is not None and value != self.exact_value:
            raise ValueError(f"{field_name} must equal pinned value {self.exact_value!r}")
        if (
            source is BoundSource.ENGINEERING_FALLBACK
            and self.engineering_fallback_value is not None
            and value != self.engineering_fallback_value
        ):
            raise ValueError(
                f"{field_name} with engineering fallback provenance must equal " f"{self.engineering_fallback_value!r}"
            )

    def to_dict(self) -> dict[str, Any]:
        return {
            "allowed_sources": [item.value for item in self.allowed_sources],
            "exact_value": self.exact_value,
            "engineering_fallback_value": self.engineering_fallback_value,
        }


