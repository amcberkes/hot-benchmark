@dataclass(frozen=True, slots=True)
class InstrumentationReceipt:
    """Whole-model and per-target binding for a mutation sequence."""

    mode: InstrumentationMode
    source_model_sha256: str
    prepared_model_sha256: str
    mutation_sequence_sha256: str
    targets: tuple[MutationTargetState, ...]
    version: str = INSTRUMENTATION_RECEIPT_VERSION

    def __post_init__(self) -> None:
        version = _exact_text(self.version, field_name="version")
        if version != INSTRUMENTATION_RECEIPT_VERSION:
            raise ValueError(f"instrumentation receipt version must be {INSTRUMENTATION_RECEIPT_VERSION!r}")
        object.__setattr__(self, "version", version)
        mode = _enum(self.mode, InstrumentationMode, field_name="mode")
        object.__setattr__(self, "mode", mode)
        source = _sha256(self.source_model_sha256, field_name="source_model_sha256")
        prepared = _sha256(self.prepared_model_sha256, field_name="prepared_model_sha256")
        sequence_sha = _sha256(self.mutation_sequence_sha256, field_name="mutation_sequence_sha256")
        targets = _typed_tuple(self.targets, MutationTargetState, field_name="targets")
        _casefold_tuple_unique(tuple(item.energyplus_object for item in targets), field_name="mutation targets")
        targets = tuple(sorted(targets, key=lambda item: tuple(part.casefold() for part in item.energyplus_object)))
        if mode is InstrumentationMode.PREEXISTING:
            if source != prepared or targets:
                raise ValueError("preexisting instrumentation requires identical models and no targets")
            if sequence_sha != mutation_sequence_sha256(()):
                raise ValueError("preexisting instrumentation requires an empty mutation sequence")
        else:
            if source == prepared:
                raise ValueError("generated instrumentation must change the model")
            if not targets:
                raise ValueError("generated instrumentation requires mutation targets")
        object.__setattr__(self, "source_model_sha256", source)
        object.__setattr__(self, "prepared_model_sha256", prepared)
        object.__setattr__(self, "mutation_sequence_sha256", sequence_sha)
        object.__setattr__(self, "targets", targets)

    def to_dict(self) -> dict[str, Any]:
        return {
            "version": self.version,
            "mode": self.mode.value,
            "source_model_sha256": self.source_model_sha256,
            "prepared_model_sha256": self.prepared_model_sha256,
            "mutation_sequence_sha256": self.mutation_sequence_sha256,
            "targets": [item.to_dict() for item in self.targets],
        }

    @classmethod
    def from_dict(cls, value: Any) -> InstrumentationReceipt:
        item = _exact_keys(
            value,
            required=frozenset(
                {
                    "version",
                    "mode",
                    "source_model_sha256",
                    "prepared_model_sha256",
                    "mutation_sequence_sha256",
                    "targets",
                }
            ),
            field_name="instrumentation receipt",
        )
        return cls(
            version=item["version"],
            mode=item["mode"],
            source_model_sha256=item["source_model_sha256"],
            prepared_model_sha256=item["prepared_model_sha256"],
            mutation_sequence_sha256=item["mutation_sequence_sha256"],
            targets=tuple(
                MutationTargetState.from_dict(entry)
                for entry in _tuple(item["targets"], field_name="instrumentation receipt.targets")
            ),
        )


