"""Immutable control-capability contracts for instrumented EnergyPlus models.

This module is intentionally dependency-free.  It defines the artifact boundary
between future HVAC discovery/instrumentation code and the HOT runtime without
changing the current thermostat implementation.

The schema is derived from the typed equipment and actuator descriptors in the
Building2Building paper release.  HOT pins that source exactly and strengthens
its contracts: names are unique under EnergyPlus' case-insensitive semantics,
action order is canonical, fixed values are validated, and every topology and
mutation reference must resolve before a manifest can be constructed.
"""

