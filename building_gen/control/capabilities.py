@dataclass(frozen=True, slots=True)
class ProfileChannelContract:
    """Exact channel composition, scope, endpoint, role, and bounds contract."""

    channel: ControlChannel
    scope: ChannelScope
    hot_order: int
    unit: PhysicalUnit
    role: ActuatorRole
    allowed_energyplus_pairs: tuple[EnergyPlusActuatorPair, ...]
    control_node_kinds: tuple[TopologyNodeKind, ...]
    lower_bound: BoundRequirement
    upper_bound: BoundRequirement
    effect_semantics: tuple[OutputVariableSemantic, ...]
    fixed_value: float | None = None

    def __post_init__(self) -> None:
        object.__setattr__(self, "channel", _enum(self.channel, ControlChannel, field_name="channel"))
        object.__setattr__(self, "scope", _enum(self.scope, ChannelScope, field_name="scope"))
        object.__setattr__(self, "unit", _enum(self.unit, PhysicalUnit, field_name="unit"))
        role = _enum(self.role, ActuatorRole, field_name="role")
        object.__setattr__(self, "role", role)
        if isinstance(self.hot_order, bool) or not isinstance(self.hot_order, int) or self.hot_order < 0:
            raise ValueError("hot_order must be a non-negative integer")
        pairs = _typed_tuple(
            self.allowed_energyplus_pairs,
            EnergyPlusActuatorPair,
            field_name="allowed_energyplus_pairs",
        )
        if not pairs:
            raise ValueError("allowed_energyplus_pairs cannot be empty")
        _casefold_tuple_unique(
            tuple((item.component_type, item.control_type) for item in pairs),
            field_name="allowed EnergyPlus actuator pairs",
        )
        object.__setattr__(
            self,
            "allowed_energyplus_pairs",
            tuple(sorted(pairs, key=lambda item: (item.component_type.casefold(), item.control_type.casefold()))),
        )
        kinds = tuple(
            _enum(item, TopologyNodeKind, field_name="control node kind")
            for item in _tuple(self.control_node_kinds, field_name="control_node_kinds")
        )
        if not kinds:
            raise ValueError("control_node_kinds cannot be empty")
        _casefold_unique(tuple(item.value for item in kinds), field_name="control_node_kinds")
        object.__setattr__(self, "control_node_kinds", tuple(sorted(kinds, key=lambda item: item.value)))
        if not isinstance(self.lower_bound, BoundRequirement) or not isinstance(self.upper_bound, BoundRequirement):
            raise TypeError("profile bounds must be BoundRequirement values")
        semantics = tuple(
            _enum(item, OutputVariableSemantic, field_name="effect semantic")
            for item in _tuple(self.effect_semantics, field_name="effect_semantics")
        )
        if not semantics:
            raise ValueError("effect_semantics cannot be empty")
        _casefold_unique(tuple(item.value for item in semantics), field_name="effect_semantics")
        object.__setattr__(self, "effect_semantics", tuple(sorted(semantics, key=lambda item: item.value)))

        if role is ActuatorRole.AGENT:
            if self.fixed_value is not None:
                raise ValueError("agent channel contracts cannot declare fixed_value")
        else:
            if self.fixed_value is None:
                raise ValueError("fixed channel contracts require fixed_value")
            fixed = _finite_float(self.fixed_value, field_name="fixed_value")
            object.__setattr__(self, "fixed_value", fixed)

    @property
    def energyplus_pairs(self) -> frozenset[tuple[str, str]]:
        return frozenset((item.component_type, item.control_type) for item in self.allowed_energyplus_pairs)

    def to_dict(self) -> dict[str, Any]:
        return {
            "channel": self.channel.value,
            "scope": self.scope.value,
            "hot_order": self.hot_order,
            "unit": self.unit.value,
            "role": self.role.value,
            "allowed_energyplus_pairs": [item.to_dict() for item in self.allowed_energyplus_pairs],
            "control_node_kinds": [item.value for item in self.control_node_kinds],
            "lower_bound": self.lower_bound.to_dict(),
            "upper_bound": self.upper_bound.to_dict(),
            "effect_semantics": [item.value for item in self.effect_semantics],
            "fixed_value": self.fixed_value,
        }


@dataclass(frozen=True, slots=True)
class ControlProfile:
    """One versioned physical-endpoint profile for an HVAC family.

    Profiles constrain discovered actuator endpoints, not Gym command
    transforms.  That distinction preserves the existing thermostat
    ``heating_setpoint_c + cooling_offset_c`` runtime while the later binding
    layer maps its two commands onto the two physical schedule endpoints.
    """

    profile_id: str
    family: EquipmentFamily
    upstream_family: str
    equipment_object_types: tuple[str, ...]
    equipment_node_kind: TopologyNodeKind
    minimum_served_entities: int
    maximum_served_entities: int | None
    channels: tuple[ProfileChannelContract, ...]
    required_observation_semantics: tuple[OutputVariableSemantic, ...]

    def __post_init__(self) -> None:
        object.__setattr__(self, "profile_id", _identifier(self.profile_id, field_name="profile_id"))
        object.__setattr__(self, "family", _enum(self.family, EquipmentFamily, field_name="family"))
        object.__setattr__(
            self,
            "upstream_family",
            _exact_text(self.upstream_family, field_name="upstream_family"),
        )
        object_types = tuple(
            _exact_text(item, field_name="equipment_object_types item")
            for item in _tuple(self.equipment_object_types, field_name="equipment_object_types")
        )
        if not object_types:
            raise ValueError("equipment_object_types cannot be empty")
        _casefold_unique(object_types, field_name="equipment_object_types")
        object.__setattr__(self, "equipment_object_types", tuple(sorted(object_types, key=str.casefold)))
        object.__setattr__(
            self,
            "equipment_node_kind",
            _enum(self.equipment_node_kind, TopologyNodeKind, field_name="equipment_node_kind"),
        )
        if (
            isinstance(self.minimum_served_entities, bool)
            or not isinstance(self.minimum_served_entities, int)
            or self.minimum_served_entities <= 0
        ):
            raise ValueError("minimum_served_entities must be a positive integer")
        if self.maximum_served_entities is not None:
            if (
                isinstance(self.maximum_served_entities, bool)
                or not isinstance(self.maximum_served_entities, int)
                or self.maximum_served_entities < self.minimum_served_entities
            ):
                raise ValueError("maximum_served_entities must be at least minimum_served_entities")
        channels = _typed_tuple(self.channels, ProfileChannelContract, field_name="channels")
        if not channels:
            raise ValueError("profile channels cannot be empty")
        _casefold_unique(tuple(item.channel.value for item in channels), field_name="profile channels")
        orders = tuple(sorted(item.hot_order for item in channels))
        if orders != tuple(range(len(channels))):
            raise ValueError("profile hot_order values must be unique and contiguous from zero")
        object.__setattr__(self, "channels", tuple(sorted(channels, key=lambda item: item.hot_order)))
        observations = tuple(
            _enum(item, OutputVariableSemantic, field_name="required observation semantic")
            for item in _tuple(
                self.required_observation_semantics,
                field_name="required_observation_semantics",
            )
        )
        if not observations:
            raise ValueError("required_observation_semantics cannot be empty")
        _casefold_unique(
            tuple(item.value for item in observations),
            field_name="required_observation_semantics",
        )
        object.__setattr__(
            self,
            "required_observation_semantics",
            tuple(sorted(observations, key=lambda item: item.value)),
        )

    def channel_contract(self, channel: ControlChannel) -> ProfileChannelContract:
        for item in self.channels:
            if item.channel is channel:
                return item
        raise KeyError(f"profile {self.profile_id!r} has no channel {channel.value!r}")

    def to_dict(self) -> dict[str, Any]:
        return {
            "profile_id": self.profile_id,
            "family": self.family.value,
            "upstream_family": self.upstream_family,
            "equipment_object_types": list(self.equipment_object_types),
            "equipment_node_kind": self.equipment_node_kind.value,
            "minimum_served_entities": self.minimum_served_entities,
            "maximum_served_entities": self.maximum_served_entities,
            "channels": [item.to_dict() for item in self.channels],
            "required_observation_semantics": [item.value for item in self.required_observation_semantics],
        }


