@dataclass(frozen=True, slots=True)
class ActuatorDescriptor:
    """One exact EnergyPlus actuator endpoint and its physical contract."""

    profile_id: str
    equipment_id: str
    control_node_id: str
    affected_entity_ids: tuple[str, ...]
    family: EquipmentFamily
    channel: ControlChannel
    component_type: str
    control_type: str
    component_name: str
    unit: PhysicalUnit
    lower_bound: float
    upper_bound: float
    lower_bound_source: BoundSource
    upper_bound_source: BoundSource
    role: ActuatorRole = ActuatorRole.AGENT
    fixed_value: float | None = None

    def __post_init__(self) -> None:
        profile_id = _identifier(self.profile_id, field_name="profile_id")
        profile = control_profile_by_id(profile_id)
        object.__setattr__(self, "profile_id", profile_id)
        object.__setattr__(self, "equipment_id", _exact_text(self.equipment_id, field_name="equipment_id"))
        object.__setattr__(
            self,
            "control_node_id",
            _exact_text(self.control_node_id, field_name="control_node_id"),
        )
        affected = tuple(
            _exact_text(item, field_name="affected_entity_ids item")
            for item in _tuple(self.affected_entity_ids, field_name="affected_entity_ids")
        )
        if not affected:
            raise ValueError("affected_entity_ids cannot be empty")
        _casefold_unique(affected, field_name="affected_entity_ids")
        object.__setattr__(
            self,
            "affected_entity_ids",
            tuple(sorted(affected, key=str.casefold)),
        )
        family = _enum(self.family, EquipmentFamily, field_name="family")
        channel = _enum(self.channel, ControlChannel, field_name="channel")
        unit = _enum(self.unit, PhysicalUnit, field_name="unit")
        lower_source = _enum(
            self.lower_bound_source,
            BoundSource,
            field_name="lower_bound_source",
        )
        upper_source = _enum(
            self.upper_bound_source,
            BoundSource,
            field_name="upper_bound_source",
        )
        role = _enum(self.role, ActuatorRole, field_name="role")
        object.__setattr__(self, "family", family)
        object.__setattr__(self, "channel", channel)
        object.__setattr__(self, "unit", unit)
        object.__setattr__(self, "lower_bound_source", lower_source)
        object.__setattr__(self, "upper_bound_source", upper_source)
        object.__setattr__(self, "role", role)
        for field_name in ("component_type", "control_type", "component_name"):
            object.__setattr__(
                self,
                field_name,
                _exact_text(getattr(self, field_name), field_name=field_name),
            )
        lower = _finite_float(self.lower_bound, field_name="lower_bound")
        upper = _finite_float(self.upper_bound, field_name="upper_bound")
        if lower >= upper:
            raise ValueError("lower_bound must be smaller than upper_bound")
        object.__setattr__(self, "lower_bound", lower)
        object.__setattr__(self, "upper_bound", upper)

        if family is not profile.family:
            raise ValueError(f"profile {profile_id!r} requires family {profile.family.value!r}")
        try:
            contract = profile.channel_contract(channel)
        except KeyError as error:
            raise ValueError(f"channel {channel.value!r} is not part of profile {profile_id!r}") from error
        if unit is not contract.unit:
            raise ValueError(f"channel {channel.value!r} requires unit {contract.unit.value!r}")
        if (self.component_type, self.control_type) not in contract.energyplus_pairs:
            raise ValueError(f"channel {channel.value!r} has a noncanonical EnergyPlus component/control pair")
        if role is not contract.role:
            raise ValueError(
                f"channel {channel.value!r} in profile {profile_id!r} requires role {contract.role.value!r}"
            )
        contract.lower_bound.validate(lower, lower_source, field_name="lower_bound")
        contract.upper_bound.validate(upper, upper_source, field_name="upper_bound")

        if contract.fixed_value is None:
            if self.fixed_value is not None:
                raise ValueError("agent actuators cannot declare fixed_value")
        else:
            if self.fixed_value is None:
                raise ValueError("fixed actuators require fixed_value")
            fixed = _finite_float(self.fixed_value, field_name="fixed_value")
            if fixed != contract.fixed_value:
                raise ValueError(f"channel {channel.value!r} requires fixed_value {contract.fixed_value!r}")
            if not lower <= fixed <= upper:
                raise ValueError("fixed_value must lie within inclusive actuator bounds")
            object.__setattr__(self, "fixed_value", fixed)

    @property
    def energyplus_triple(self) -> tuple[str, str, str]:
        return self.component_type, self.control_type, self.component_name

    def endpoint_identity(self) -> dict[str, Any]:
        return {
            "component_type": self.component_type,
            "control_type": self.control_type,
            "component_name": self.component_name,
        }

    @property
    def endpoint_id(self) -> str:
        return energyplus_actuator_endpoint_id(*self.energyplus_triple)

    def to_dict(self) -> dict[str, Any]:
        return {
            "endpoint_id": self.endpoint_id,
            "profile_id": self.profile_id,
            "equipment_id": self.equipment_id,
            "control_node_id": self.control_node_id,
            "affected_entity_ids": list(self.affected_entity_ids),
            "family": self.family.value,
            "channel": self.channel.value,
            "energyplus": self.endpoint_identity(),
            "unit": self.unit.value,
            "lower_bound": self.lower_bound,
            "upper_bound": self.upper_bound,
            "lower_bound_source": self.lower_bound_source.value,
            "upper_bound_source": self.upper_bound_source.value,
            "role": self.role.value,
            "fixed_value": self.fixed_value,
        }

    @classmethod
    def from_dict(cls, value: Any) -> ActuatorDescriptor:
        item = _exact_keys(
            value,
            required=frozenset(
                {
                    "endpoint_id",
                    "profile_id",
                    "equipment_id",
                    "control_node_id",
                    "affected_entity_ids",
                    "family",
                    "channel",
                    "energyplus",
                    "unit",
                    "lower_bound",
                    "upper_bound",
                    "lower_bound_source",
                    "upper_bound_source",
                    "role",
                    "fixed_value",
                }
            ),
            field_name="actuator",
        )
        energyplus = _exact_keys(
            item["energyplus"],
            required=frozenset({"component_type", "control_type", "component_name"}),
            field_name="actuator.energyplus",
        )
        descriptor = cls(
            profile_id=item["profile_id"],
            equipment_id=item["equipment_id"],
            control_node_id=item["control_node_id"],
            affected_entity_ids=_tuple(
                item["affected_entity_ids"],
                field_name="affected_entity_ids",
            ),
            family=item["family"],
            channel=item["channel"],
            component_type=energyplus["component_type"],
            control_type=energyplus["control_type"],
            component_name=energyplus["component_name"],
            unit=item["unit"],
            lower_bound=item["lower_bound"],
            upper_bound=item["upper_bound"],
            lower_bound_source=item["lower_bound_source"],
            upper_bound_source=item["upper_bound_source"],
            role=item["role"],
            fixed_value=item["fixed_value"],
        )
        endpoint_id = _exact_text(item["endpoint_id"], field_name="endpoint_id")
        if endpoint_id != descriptor.endpoint_id:
            raise ValueError("actuator endpoint_id does not match its canonical identity")
        return descriptor


@dataclass(frozen=True, slots=True)
class EquipmentDescriptor:
    """One supported HVAC equipment object and the entities it serves."""

    profile_id: str
    equipment_id: str
    family: EquipmentFamily
    object_type: str
    object_name: str
    served_entity_ids: tuple[str, ...]

    def __post_init__(self) -> None:
        profile_id = _identifier(self.profile_id, field_name="profile_id")
        profile = control_profile_by_id(profile_id)
        object.__setattr__(self, "profile_id", profile_id)
        equipment_id = _exact_text(self.equipment_id, field_name="equipment_id")
        family = _enum(self.family, EquipmentFamily, field_name="family")
        object.__setattr__(self, "family", family)
        object.__setattr__(self, "object_type", _exact_text(self.object_type, field_name="object_type"))
        object.__setattr__(self, "object_name", _exact_text(self.object_name, field_name="object_name"))
        if family is not profile.family:
            raise ValueError(f"profile {profile_id!r} requires family {profile.family.value!r}")
        if self.object_type not in profile.equipment_object_types:
            raise ValueError(f"profile {profile_id!r} does not allow equipment object type {self.object_type!r}")
        expected_id = energyplus_topology_node_id(
            profile.equipment_node_kind,
            self.object_type,
            self.object_name,
        )
        if equipment_id != expected_id:
            raise ValueError(f"equipment_id must equal deterministic EnergyPlus identity {expected_id!r}")
        object.__setattr__(self, "equipment_id", equipment_id)
        entities = tuple(
            _exact_text(item, field_name="served_entity_ids item")
            for item in _tuple(self.served_entity_ids, field_name="served_entity_ids")
        )
        if not entities:
            raise ValueError("served_entity_ids cannot be empty")
        _casefold_unique(entities, field_name="served_entity_ids")
        if len(entities) < profile.minimum_served_entities or (
            profile.maximum_served_entities is not None and len(entities) > profile.maximum_served_entities
        ):
            maximum = "unbounded" if profile.maximum_served_entities is None else str(profile.maximum_served_entities)
            raise ValueError(
                f"profile {profile_id!r} requires between "
                f"{profile.minimum_served_entities} and {maximum} served entities"
            )
        object.__setattr__(self, "served_entity_ids", tuple(sorted(entities, key=str.casefold)))

    @property
    def energyplus_object(self) -> tuple[str, str]:
        return self.object_type, self.object_name

    def to_dict(self) -> dict[str, Any]:
        return {
            "profile_id": self.profile_id,
            "equipment_id": self.equipment_id,
            "family": self.family.value,
            "energyplus": {
                "object_type": self.object_type,
                "object_name": self.object_name,
            },
            "served_entity_ids": list(self.served_entity_ids),
        }

    @classmethod
    def from_dict(cls, value: Any) -> EquipmentDescriptor:
        item = _exact_keys(
            value,
            required=frozenset({"profile_id", "equipment_id", "family", "energyplus", "served_entity_ids"}),
            field_name="equipment",
        )
        energyplus = _exact_keys(
            item["energyplus"],
            required=frozenset({"object_type", "object_name"}),
            field_name="equipment.energyplus",
        )
        return cls(
            profile_id=item["profile_id"],
            equipment_id=item["equipment_id"],
            family=item["family"],
            object_type=energyplus["object_type"],
            object_name=energyplus["object_name"],
            served_entity_ids=_tuple(item["served_entity_ids"], field_name="served_entity_ids"),
        )


@dataclass(frozen=True, slots=True)
class TopologyNode:
    """One stable entity in the HVAC/zone control graph."""

    node_id: str
    kind: TopologyNodeKind
    object_type: str | None = None
    object_name: str | None = None

    def __post_init__(self) -> None:
        node_id = _exact_text(self.node_id, field_name="node_id")
        kind = _enum(self.kind, TopologyNodeKind, field_name="kind")
        object.__setattr__(self, "kind", kind)
        if (self.object_type is None) != (self.object_name is None):
            raise ValueError("object_type and object_name must be provided together")
        if kind is TopologyNodeKind.GLOBAL:
            if self.object_type is not None or node_id != "global":
                raise ValueError("global topology node must have ID 'global' and no EnergyPlus object")
        else:
            if self.object_type is None or self.object_name is None:
                raise ValueError("non-global topology nodes require an exact EnergyPlus object")
            object_type = _exact_text(self.object_type, field_name="object_type")
            object_name = _exact_text(self.object_name, field_name="object_name")
            allowed_object_types = _TOPOLOGY_KIND_OBJECT_TYPES[kind]
            if object_type not in allowed_object_types:
                expected = ", ".join(sorted(allowed_object_types))
                raise ValueError(
                    f"topology node kind {kind.value!r} requires an exact EnergyPlus " f"object type from: {expected}"
                )
            object.__setattr__(self, "object_type", object_type)
